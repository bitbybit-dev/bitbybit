import { describe, it } from "node:test";
import assert from "node:assert/strict";
import topics from "./topics.js";

const { rulesIn, splitRedirects, movedRules, retiredProblems, redirectProblems, movedRegion, helpRegion } = topics;

const MOVED_BEGIN = "# BEGIN moved pages - generated by npm run topics when a page's address changes; do not edit by hand";
const MOVED_END = "# END moved pages";
const HELP_BEGIN = "# BEGIN /help/<topic> redirects - generated by npm run topics from each page's topic; do not edit by hand";
const HELP_END = "# END /help/<topic> redirects";

const topic = (id, url) => ({ id, url });
const rule = (from, to, status = "301") => ({ from, to, status });
const addressesOf = (...urls) => new Set(urls);

describe("movedRules", () => {
    it("should redirect a page's old address to its new one when its topic moves", () => {
        // Arrange
        const previous = [topic("composer.gui.controls", "/learn/composer/controls")];
        const now = [topic("composer.gui.controls", "/learn/composer/gui/controls")];

        // Act
        const moved = movedRules(previous, now, addressesOf("/learn/composer/gui/controls"), [], []);

        // Assert
        assert.deepEqual(moved, [rule("/learn/composer/controls", "/learn/composer/gui/controls")]);
    });

    it("should point an earlier move at the page's newest address, so no redirect leads to another", () => {
        // Arrange
        const kept = [rule("/learn/a", "/learn/b")];
        const previous = [topic("docs.page", "/learn/b")];
        const now = [topic("docs.page", "/learn/c")];

        // Act
        const moved = movedRules(previous, now, addressesOf("/learn/c"), [], kept);

        // Assert
        assert.deepEqual(moved, [rule("/learn/a", "/learn/c"), rule("/learn/b", "/learn/c")]);
    });

    it("should keep the moved block as it is when no page moved", () => {
        // Arrange
        const kept = [rule("/learn/a", "/learn/b")];
        const pages = [topic("docs.page", "/learn/b")];

        // Act
        const moved = movedRules(pages, pages, addressesOf("/learn/b"), [], kept);

        // Assert
        assert.deepEqual(moved, kept);
    });

    it("should drop a moved address that a page lives at again", () => {
        // Arrange
        const kept = [rule("/learn/a", "/learn/b")];
        const pages = [topic("docs.page", "/learn/b"), topic("docs.other", "/learn/a")];

        // Act
        const moved = movedRules(pages, pages, addressesOf("/learn/a", "/learn/b"), [], kept);

        // Assert
        assert.deepEqual(moved, []);
    });

    it("should leave an old address to the hand-written rule that takes it", () => {
        // Arrange
        const previous = [topic("docs.page", "/learn/old/page")];
        const now = [topic("docs.page", "/learn/new/page")];
        const handWritten = [rule("/learn/old/*", "/learn/new/:splat")];

        // Act
        const moved = movedRules(previous, now, addressesOf("/learn/new/page"), handWritten, []);

        // Assert
        assert.deepEqual(moved, []);
    });

    it("should follow the hand-written rule that replaces a retired page a move pointed at", () => {
        // Arrange
        const kept = [rule("/learn/a", "/learn/b")];
        const previous = [topic("docs.retired", "/learn/b"), topic("docs.successor", "/learn/c")];
        const now = [topic("docs.successor", "/learn/c")];
        const handWritten = [rule("/learn/b", "/learn/c"), rule("/help/docs.retired", "/learn/c", "302")];

        // Act
        const moved = movedRules(previous, now, addressesOf("/learn/c"), handWritten, kept);

        // Assert
        assert.deepEqual(moved, [rule("/learn/a", "/learn/c")]);
    });
});

describe("retiredProblems", () => {
    it("should name the /help/ address and the old address of a retired topic no rule takes", () => {
        // Arrange
        const previous = [topic("designer.tutorials.desk-arm.screw", "/learn/designer/tutorials/desk-arm/screw")];

        // Act
        const problems = retiredProblems(previous, [], addressesOf(), []);

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /\/help\/designer\.tutorials\.desk-arm\.screw or \/learn\/designer\/tutorials\/desk-arm\/screw/);
    });

    it("should accept a retired topic whose addresses hand-written rules take", () => {
        // Arrange
        const previous = [topic("docs.retired", "/learn/old/retired")];
        const handWritten = [rule("/learn/old/*", "/learn/new/:splat"), rule("/help/docs.retired", "/learn/new", "302")];

        // Act
        const problems = retiredProblems(previous, [], addressesOf("/learn/new"), handWritten);

        // Assert
        assert.deepEqual(problems, []);
    });

    it("should ask only for the /help/ address when a renamed topic keeps the page's address", () => {
        // Arrange
        const previous = [topic("docs.old-name", "/learn/page")];
        const now = [topic("docs.new-name", "/learn/page")];

        // Act
        const problems = retiredProblems(previous, now, addressesOf("/learn/page"), []);

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /takes \/help\/docs\.old-name:/);
    });
});

describe("redirectProblems", () => {
    it("should accept redirects to pages, sections, splats and other sites", () => {
        // Arrange
        const rules = [
            rule("/learn/old-section/*", "/learn/section/:splat"),
            rule("/learn/old-section", "/learn/section"),
            rule("/learn/old-page", "/learn/section/page#anchor"),
            rule("/old-blog", "https://bitbybit.dev/blog"),
            rule("/help/docs.page", "/learn/section/page", "302"),
        ];

        // Act
        const problems = redirectProblems(rules, addressesOf("/learn/section", "/learn/section/page"));

        // Assert
        assert.deepEqual(problems, []);
    });

    it("should report a rule that sends a live page away", () => {
        // Act
        const problems = redirectProblems([rule("/learn/section/*", "/learn/elsewhere/:splat")], addressesOf("/learn/section/page"));

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /sends the live page \/learn\/section\/page away/);
    });

    it("should report a rule that a rule above it already takes", () => {
        // Arrange
        const rules = [rule("/learn/old/*", "/learn/page"), rule("/learn/old/page", "/learn/page")];

        // Act
        const problems = redirectProblems(rules, addressesOf("/learn/page"));

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /\/learn\/old\/page never applies/);
    });

    it("should report a redirect to an address another rule redirects", () => {
        // Arrange
        const rules = [rule("/learn/a", "/learn/b"), rule("/learn/b", "/learn/c")];

        // Act
        const problems = redirectProblems(rules, addressesOf("/learn/c"));

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /\/learn\/a -> \/learn\/b -> \/learn\/c is a chain/);
    });

    it("should report a /help/ redirect that is not a 302", () => {
        // Act
        const problems = redirectProblems([rule("/help/docs.page", "/learn/page", "301")], addressesOf("/learn/page"));

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /\/help\/docs\.page is a 301/);
    });

    it("should report a redirect to a learn address that is no page or section", () => {
        // Act
        const problems = redirectProblems([rule("/learn/old", "/learn/missing")], addressesOf("/learn/page"));

        // Assert
        assert.equal(problems.length, 1);
        assert.match(problems[0], /points at \/learn\/missing/);
    });
});

describe("splitRedirects", () => {
    it("should read the moved block and keep the hand-written rules above the generated blocks", () => {
        // Arrange
        const text = `# hand\n/learn/x  /learn/y  301\n\n${MOVED_BEGIN}\n/learn/a  /learn/b  301\n${MOVED_END}\n\n${HELP_BEGIN}\n/help/docs.b  /learn/b  302\n${HELP_END}\n`;

        // Act
        const parts = splitRedirects(text);

        // Assert
        assert.equal(parts.handWritten, "# hand\n/learn/x  /learn/y  301\n\n");
        assert.deepEqual(parts.moved, [rule("/learn/a", "/learn/b")]);
    });

    it("should accept a file with the /help/ block alone, which has no moved block yet", () => {
        // Act
        const parts = splitRedirects(`/learn/x  /learn/y  301\n\n${HELP_BEGIN}\n${HELP_END}\n`);

        // Assert
        assert.deepEqual(parts, { handWritten: "/learn/x  /learn/y  301\n\n", moved: [] });
    });

    it("should refuse a hand-written rule below the generated blocks, which a rewrite would lose", () => {
        // Act
        const parts = splitRedirects(`${MOVED_BEGIN}\n${MOVED_END}\n\n${HELP_BEGIN}\n${HELP_END}\n/learn/x  /learn/y  301\n`);

        // Assert
        assert.equal(parts, undefined);
    });

    it("should refuse blocks out of order", () => {
        // Act
        const parts = splitRedirects(`${HELP_BEGIN}\n${HELP_END}\n${MOVED_BEGIN}\n${MOVED_END}\n`);

        // Assert
        assert.equal(parts, undefined);
    });
});

describe("the generated blocks", () => {
    it("should write every /help/ address as a 302 and every moved page as a 301", () => {
        // Act
        const help = rulesIn(helpRegion([topic("docs.page", "/learn/page")]));
        const moved = rulesIn(movedRegion([rule("/learn/old", "/learn/page")]));

        // Assert
        assert.deepEqual(help, [rule("/help/docs.page", "/learn/page", "302")]);
        assert.deepEqual(moved, [rule("/learn/old", "/learn/page")]);
    });
});
