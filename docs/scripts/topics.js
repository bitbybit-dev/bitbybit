#!/usr/bin/env node
const fs = require("fs");
const path = require("path");

const DOCS_DIR = path.resolve(__dirname, "..");
const LEARN_DIR = path.join(DOCS_DIR, "learn");
const ROUTE_BASE = "/learn";
const TOPICS_FILE = path.join(DOCS_DIR, "src", "data", "topics.json");
const REDIRECTS_FILE = path.join(DOCS_DIR, "static", "_redirects");
const MOVED_BEGIN = "# BEGIN moved pages - generated by npm run topics when a page's address changes; do not edit by hand";
const MOVED_END = "# END moved pages";
const HELP_BEGIN = "# BEGIN /help/<topic> redirects - generated by npm run topics from each page's topic; do not edit by hand";
const HELP_END = "# END /help/<topic> redirects";
const TOPIC = /^[a-z]+(?:-[a-z]+)*(?:\.[a-z0-9]+(?:-[a-z0-9]+)*)+$/;
const TYPES = new Set(["landing", "tutorial", "how-to", "reference", "explanation"]);
const DATE = /^\d{4}-\d{2}-\d{2}$/;

function filesUnder(dir, wanted, found = []) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            filesUnder(full, wanted, found);
        } else if (wanted(entry.name)) {
            found.push(full);
        }
    }
    return found;
}

function frontMatter(text) {
    const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
    if (!match) {
        return {};
    }
    const fields = {};
    for (const line of match[1].split(/\r?\n/)) {
        const field = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
        if (field) {
            const value = field[2].trim();
            const quoted = /^(["'])(.*)\1$/.exec(value);
            fields[field[1]] = quoted ? quoted[2] : value.replace(/\s+#.*$/, "");
        }
    }
    return fields;
}

function posix(relative) {
    return relative.split(path.sep).join("/");
}

function pageUrl(file, fields) {
    const relative = posix(path.relative(LEARN_DIR, file));
    const dir = path.posix.dirname(relative) === "." ? "" : path.posix.dirname(relative);
    const name = path.posix.basename(relative).replace(/\.mdx?$/, "");
    const inDir = (tail) => [ROUTE_BASE, dir, tail].filter((part) => part !== "").join("/");
    if (fields.slug) {
        return fields.slug.startsWith("/") ? `${ROUTE_BASE}${fields.slug === "/" ? "" : fields.slug}` : inDir(fields.slug);
    }
    const parent = path.posix.basename(dir);
    if (/^(index|readme)$/i.test(name) || (parent !== "" && name === parent)) {
        return inDir("");
    }
    return inDir(fields.id || name);
}

function titleOf(text, fields) {
    if (fields.title) {
        return fields.title;
    }
    const heading = /^#\s+(.+)$/m.exec(text.replace(/^---[\s\S]*?\n---/, ""));
    return heading ? heading[1].trim() : fields.sidebar_label || "";
}

function topicProblems(fields) {
    const problems = [];
    if (!fields.topic) {
        problems.push("no topic");
    } else if (!TOPIC.test(fields.topic)) {
        problems.push(`topic ${JSON.stringify(fields.topic)} is not <product>.<area>[.<sub>].<name>, lowercase`);
    }
    if (!TYPES.has(fields.type)) {
        problems.push(`type ${JSON.stringify(fields.type || "")} is not one of ${[...TYPES].join(", ")}`);
    }
    if (fields.verified !== undefined && !DATE.test(fields.verified)) {
        problems.push(`verified ${JSON.stringify(fields.verified)} is not a yyyy-mm-dd date`);
    }
    return problems;
}

function collect() {
    const topics = [];
    const failures = [];
    for (const file of filesUnder(LEARN_DIR, (name) => /\.mdx?$/.test(name))) {
        const text = fs.readFileSync(file, "utf8");
        const fields = frontMatter(text);
        const problems = topicProblems(fields);
        failures.push(...problems.map((problem) => [file, problem]));
        if (problems.length === 0) {
            topics.push({
                id: fields.topic,
                title: titleOf(text, fields),
                type: fields.type,
                url: pageUrl(file, fields),
                path: posix(path.relative(DOCS_DIR, file)),
                ...(fields.verified ? { verified: fields.verified } : {}),
            });
        }
    }
    const sections = [];
    for (const file of filesUnder(LEARN_DIR, (name) => name === "_category_.json")) {
        const category = JSON.parse(fs.readFileSync(file, "utf8"));
        const slug = category.link && category.link.type === "generated-index" ? category.link.slug : undefined;
        if (slug && slug.startsWith("/")) {
            sections.push(`${ROUTE_BASE}${slug}`);
        }
        const topic = category.customProps && category.customProps.topic;
        if (topic === undefined) {
            continue;
        }
        if (!TOPIC.test(topic)) {
            failures.push([file, `customProps.topic ${JSON.stringify(topic)} is not <product>.<area>[.<sub>].<name>, lowercase`]);
        } else if (!slug || !slug.startsWith("/")) {
            failures.push([file, "a section with a topic needs a generated-index link with an absolute slug, so its address is fixed"]);
        } else {
            topics.push({ id: topic, title: category.link.title || category.label, type: "landing", url: `${ROUTE_BASE}${slug}`, path: posix(path.relative(DOCS_DIR, file)) });
        }
    }
    const owners = new Map();
    for (const topic of topics) {
        if (owners.has(topic.id)) {
            failures.push([path.join(DOCS_DIR, topic.path), `topic ${topic.id} is already ${owners.get(topic.id)}'s`]);
        } else {
            owners.set(topic.id, topic.path);
        }
    }
    const urls = new Map();
    for (const topic of topics) {
        if (urls.has(topic.url)) {
            failures.push([path.join(DOCS_DIR, topic.path), `${topic.url} is also ${urls.get(topic.url)}'s address`]);
        } else {
            urls.set(topic.url, topic.path);
        }
    }
    topics.sort((a, b) => a.id.localeCompare(b.id));
    return { topics, sections, failures };
}

function rulesIn(text) {
    return text
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line !== "" && !line.startsWith("#"))
        .map((line) => {
            const [from, to, status] = line.split(/\s+/);
            return { from, to, status: status || "302" };
        });
}

function isDynamic(url) {
    return /\*|\/:/.test(url);
}

function addressOf(url) {
    return url.replace(/[?#].*$/, "");
}

function sourcePattern(from) {
    const pattern = from
        .replace(/[.+?^${}()|[\]\\]/g, "\\$&")
        .replace(/\*/g, ".*")
        .replace(/\/:[A-Za-z]\w*/g, "/[^/]+");
    return new RegExp(`^${pattern}$`);
}

function splitRedirects(redirects) {
    const [movedBegin, movedEnd, helpBegin, helpEnd] = [MOVED_BEGIN, MOVED_END, HELP_BEGIN, HELP_END].map((mark) => redirects.indexOf(mark));
    if ([movedBegin, movedEnd, helpBegin, helpEnd].every((index) => index < 0)) {
        return { handWritten: redirects, moved: [] };
    }
    const hasMoved = movedBegin >= 0 || movedEnd >= 0;
    const marks = hasMoved ? [movedBegin, movedEnd, helpBegin, helpEnd] : [helpBegin, helpEnd];
    const ordered = marks.every((index, i) => index >= 0 && (i === 0 || index > marks[i - 1]));
    if (!ordered || redirects.slice(helpEnd + HELP_END.length).trim() !== "" || (hasMoved && redirects.slice(movedEnd + MOVED_END.length, helpBegin).trim() !== "")) {
        return undefined;
    }
    return {
        handWritten: redirects.slice(0, marks[0]),
        moved: hasMoved ? rulesIn(redirects.slice(movedBegin + MOVED_BEGIN.length, movedEnd)) : [],
    };
}

function movedRules(previous, topics, addresses, handWritten, kept) {
    const now = new Map(topics.map((topic) => [topic.id, topic.url]));
    const moves = new Map(kept.map((rule) => [rule.from, rule.to]));
    for (const topic of previous) {
        const url = now.get(topic.id);
        if (url !== undefined && url !== topic.url) {
            moves.set(topic.url, url);
        }
    }
    const steps = new Map([...moves, ...handWritten.filter((rule) => !isDynamic(rule.from) && !isDynamic(rule.to)).map((rule) => [rule.from, rule.to])]);
    const resolve = (url) => {
        const seen = new Set();
        let at = url;
        while (steps.has(at) && !addresses.has(at) && !seen.has(at)) {
            seen.add(at);
            at = steps.get(at);
        }
        return at;
    };
    const handPatterns = handWritten.map((rule) => sourcePattern(rule.from));
    return [...moves]
        .filter(([from]) => !addresses.has(from) && !handPatterns.some((pattern) => pattern.test(from)))
        .map(([from, to]) => ({ from, to: resolve(to), status: "301" }))
        .filter((rule) => rule.from !== rule.to)
        .sort((a, b) => a.from.localeCompare(b.from));
}

function retiredProblems(previous, topics, addresses, handWritten) {
    const ids = new Set(topics.map((topic) => topic.id));
    const handPatterns = handWritten.map((rule) => sourcePattern(rule.from));
    return previous
        .filter((topic) => !ids.has(topic.id))
        .flatMap((topic) => {
            const unserved = [`/help/${topic.id}`, ...(addresses.has(topic.url) ? [] : [topic.url])].filter((url) => !handPatterns.some((pattern) => pattern.test(url)));
            return unserved.length === 0
                ? []
                : [`topic ${topic.id} left ${topic.url} and no hand-written rule takes ${unserved.join(" or ")}: add one above the generated blocks, pointing at the page that replaces it`];
        });
}

function redirectProblems(rules, addresses) {
    const patterns = rules.map((rule) => sourcePattern(rule.from));
    const firstMatch = (url) => patterns.findIndex((pattern) => pattern.test(url));
    const problems = [];
    rules.forEach((rule, index) => {
        const page = [...addresses].find((url) => patterns[index].test(url));
        if (page !== undefined) {
            problems.push(`${rule.from} sends the live page ${page} away: a redirect wins over a page at its address`);
        }
        const earlier = firstMatch(rule.from);
        if (earlier < index) {
            problems.push(`${rule.from} never applies: ${rules[earlier].from} above it takes the same address first`);
        }
        if (rule.from.startsWith("/help/") && rule.status !== "302") {
            problems.push(`${rule.from} is a ${rule.status}: a /help/ address follows its topic's page wherever it moves, so it is a 302 that browsers do not keep`);
        }
        if (!isDynamic(rule.to) && rule.to.startsWith("/")) {
            const target = addressOf(rule.to);
            const next = firstMatch(target);
            if (next >= 0) {
                problems.push(`${rule.from} -> ${rule.to} -> ${rules[next].to} is a chain: point ${rule.from} at the end of it`);
            } else if ((target === ROUTE_BASE || target.startsWith(`${ROUTE_BASE}/`)) && !addresses.has(target)) {
                problems.push(`${rule.from} points at ${rule.to}, which is no learn page or section`);
            }
        }
    });
    return problems;
}

function movedRegion(moved) {
    const width = Math.max(0, ...moved.map((rule) => rule.from.length));
    return [MOVED_BEGIN, ...moved.map((rule) => `${rule.from.padEnd(width)}  ${rule.to}  301`), MOVED_END].join("\n");
}

function helpRegion(topics) {
    const width = Math.max(...topics.map((topic) => topic.id.length)) + "/help/".length;
    return [HELP_BEGIN, ...topics.map((topic) => `${`/help/${topic.id}`.padEnd(width)}  ${topic.url}  302`), HELP_END].join("\n");
}

function main() {
    const check = process.argv.includes("--check");
    const { topics, sections, failures } = collect();
    if (failures.length > 0) {
        console.error(`\n${failures.length} problem(s) with the learn pages' topics. Every page carries "topic:" and "type:" front matter:\n`);
        for (const [file, why] of failures) {
            console.error(`  ${posix(path.relative(DOCS_DIR, file))}\n      ${why}`);
        }
        process.exit(1);
    }
    const parts = splitRedirects(fs.readFileSync(REDIRECTS_FILE, "utf8"));
    if (parts === undefined) {
        console.error(`static/_redirects has broken generated blocks: keep "${MOVED_BEGIN}", "${MOVED_END}", "${HELP_BEGIN}" and "${HELP_END}" in that order at the end of the file, below every hand-written rule, or remove all four.`);
        process.exit(1);
    }
    const addresses = new Set([...topics.map((topic) => topic.url), ...sections]);
    const previous = fs.existsSync(TOPICS_FILE) ? JSON.parse(fs.readFileSync(TOPICS_FILE, "utf8")) : [];
    const handWritten = rulesIn(parts.handWritten);
    const moved = movedRules(previous, topics, addresses, handWritten, parts.moved);
    const redirects = `${[parts.handWritten.replace(/\s*$/, ""), movedRegion(moved), helpRegion(topics)].filter((part) => part !== "").join("\n\n")}\n`;
    const problems = [...retiredProblems(previous, topics, addresses, handWritten), ...redirectProblems(rulesIn(redirects), addresses)];
    if (problems.length > 0) {
        console.error(`\n${problems.length} problem(s) with static/_redirects:\n`);
        for (const problem of problems) {
            console.error(`  ${problem}`);
        }
        process.exit(1);
    }
    const topicsText = `${JSON.stringify(topics, null, 2)}\n`;
    if (check) {
        const stale = [
            ...(fs.existsSync(TOPICS_FILE) && fs.readFileSync(TOPICS_FILE, "utf8") === topicsText ? [] : ["src/data/topics.json"]),
            ...(fs.readFileSync(REDIRECTS_FILE, "utf8") === redirects ? [] : ["the generated blocks of static/_redirects"]),
        ];
        if (stale.length > 0) {
            console.error(`Out of date with the pages' topics: ${stale.join(" and ")}. Run npm run topics and commit the result.`);
            process.exit(1);
        }
        console.log(`Every learn page carries a topic and a type: ${topics.length} topics, each with one address and a /help redirect, and ${moved.length} moved-page redirect(s).`);
        return;
    }
    fs.writeFileSync(REDIRECTS_FILE, redirects);
    fs.writeFileSync(TOPICS_FILE, topicsText);
    const added = moved.filter((rule) => !parts.moved.some((kept) => kept.from === rule.from && kept.to === rule.to));
    console.log(`Wrote ${topics.length} topics to src/data/topics.json, and their /help redirects and ${moved.length} moved-page redirect(s) to static/_redirects.`);
    for (const rule of added) {
        console.log(`  moved: ${rule.from} -> ${rule.to}`);
    }
}

if (require.main === module) {
    main();
}

module.exports = { rulesIn, splitRedirects, movedRules, retiredProblems, redirectProblems, movedRegion, helpRegion };
