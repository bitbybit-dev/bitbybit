/** The type names a field may resolve a class through: a plain reference, or each side of an intersection. */
function typeNames(type) {
    if (!type) return [];
    if (ts.isIntersectionTypeNode(type)) return type.types.flatMap(typeNames);
    if (ts.isTypeReferenceNode(type) && ts.isIdentifier(type.typeName)) return [type.typeName.text];
    return [];
}

/* ----------------------------------------------------------------------- reading a doc */

function docOf(node) {
    const blocks = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc);
    const block = blocks[blocks.length - 1];
    if (!block) return null;
    const tags = (block.tags ?? []).map((tag) => ({
        name: tag.tagName.text,
        text: (ts.getTextOfJSDocComment(tag.comment) ?? "").trim(),
        param: ts.isJSDocParameterTag(tag) && ts.isIdentifier(tag.name) ? tag.name.text : undefined,
    }));
    return { description: (ts.getTextOfJSDocComment(block.comment) ?? "").trim(), tags };
}
const leadingBlocks = (node, sf) => (ts.getLeadingCommentRanges(sf.text, node.getFullStart()) || []).filter((r) => sf.text.substring(r.pos, r.pos + 3) === "/**").length;
const words = (text) => text.replace(/`[^`]*`/g, " code ").split(/\s+/).filter(Boolean);
const firstParagraph = (text) => text.split(/\n\s*\n/)[0] ?? "";

const STOP = new Set(["a", "an", "the", "of", "to", "and", "or", "in", "on", "for", "with", "from", "by", "is", "are", "this", "that", "as", "at", "it", "its"]);
const VENDOR = new Set(["opencascade", "occt", "jscad", "manifold", "babylonjs", "babylon", "threejs", "three", "playcanvas", "openCascade"]);
const stem = (w) => w.replace(/(ies)$/, "y").replace(/(es|s)$/, "").replace(/(ing|ed)$/, "");
const nameTokens = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[_.]/g, " ").toLowerCase().split(/\s+/).filter(Boolean).map(stem);
