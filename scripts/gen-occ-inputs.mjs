#!/usr/bin/env node
/**
 * Assemble packages/dev/occt/lib/api/inputs/occ-inputs.ts from its fragments.
 *
 * The OCCT inputs are one `export namespace OCCT` of some 300 DTO classes, enums and pointer types.
 * TypeScript cannot merge a namespace across modules, the declarations bundle that feeds the visual
 * editors is assembled from the emitted .d.ts, and the component generator matches DTOs on the
 * innermost namespace name - so the namespace has to stay one compilation unit. What is split is the
 * authoring: every file in lib/api/inputs/occt/ holds a slice of the namespace body, unindented and
 * with imports so it reads and type-checks as an ordinary module, and this script writes them back into
 * the namespace, in file-name order, indented by four spaces. The fragments' imports are dropped (the
 * assembled file carries the namespace's own three); 00-namespace.ts holds the namespace's doc comment.
 *
 * The assembled file is committed: nothing runs at build time, and `--check` in `npm test` fails when
 * the committed file is not what the fragments assemble to.
 *
 *   node scripts/gen-occ-inputs.mjs           write occ-inputs.ts
 *   node scripts/gen-occ-inputs.mjs --check   write nothing; fail if occ-inputs.ts would change
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const DIR = path.join(ROOT, "packages/dev/occt/lib/api/inputs/occt");
const OUT = path.join(ROOT, "packages/dev/occt/lib/api/inputs/occ-inputs.ts");

const HEADER = [
    "/* eslint-disable @typescript-eslint/no-namespace */",
    "import { Base } from \"@bitbybit-dev/base\";",
    "import { IO } from \"@bitbybit-dev/base/lib/api/inputs/io-inputs\";",
    "import * as Models from \"../models\"",
    "// GENERATED by scripts/gen-occ-inputs.mjs from the fragments in ./occt/ - do not edit; edit a fragment and run `npm run gen:occ-inputs`.",
];

/**
 * A fragment's body: everything after its header, which is the run of `//` comment lines and imports
 * up to the first blank line. A `//` comment that opens the body itself therefore survives - the
 * slicer always leaves one blank line between header and body.
 */
function fragmentBody(file) {
    const lines = readFileSync(file, "utf8").split("\n");
    if (lines[lines.length - 1] === "") lines.pop();
    let i = 0;
    while (i < lines.length && lines[i] !== "" && (lines[i].startsWith("// ") || /^import /.test(lines[i]))) i++;
    if (lines[i] !== "") throw new Error(`${path.relative(ROOT, file)}: a blank line must separate the header (comments and imports) from the body`);
    return lines.slice(i + 1);
}

const files = readdirSync(DIR).filter((f) => f.endsWith(".ts")).sort();
if (!files.includes("00-namespace.ts")) throw new Error(`${DIR}: 00-namespace.ts (the namespace doc) is missing`);
const doc = fragmentBody(path.join(DIR, "00-namespace.ts"));
if (!doc.length || !doc[0].startsWith("/**") || !doc[doc.length - 1].startsWith(" */")) throw new Error("00-namespace.ts must hold exactly the namespace's JSDoc block");
const out = [...HEADER, "", ...doc, "export namespace OCCT {"];
for (const f of files) {
    if (f === "00-namespace.ts") continue;
    for (const line of fragmentBody(path.join(DIR, f))) out.push(line === "" ? "" : "    " + line);
}
out.push("}", "");
const text = out.join("\n");

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
if (current === text) { console.log(`occ-inputs.ts is what its ${files.length - 1} fragments assemble to`); process.exit(0); }
if (check) {
    const a = (current || "").split("\n"), b = text.split("\n");
    let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++;
    console.error(`occ-inputs check FAILED: occ-inputs.ts differs from its fragments (first difference at line ${i + 1}); run \`npm run gen:occ-inputs\` and commit the result`);
    process.exit(1);
}
writeFileSync(OUT, text);
console.log(`occ-inputs.ts written from ${files.length - 1} fragments (${out.length} lines)`);
