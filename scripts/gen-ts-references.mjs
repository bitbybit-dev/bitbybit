#!/usr/bin/env node
// Generates the TypeScript project references of the workspace from the package manifests, so the
// build order has one source: packages/dev/*/package.json. Every package that builds with
// tsconfig.bitbybit.json becomes a composite project whose `references` are the @bitbybit-dev/*
// siblings it declares, and tsconfig.build.json at the root references all of them - `tsc -b`
// then orders the builds itself, and `pnpm -r run build-p` orders the staging the same way, from
// the same manifests. The build info is written INTO dist/ on purpose: tsc -b trusts it over the
// outputs when it decides a project is up to date, so it has to disappear with the dist it
// describes, or a deleted dist would "rebuild" to nothing. `--check` writes nothing and exits 1
// when any generated file on disk differs from what the manifests say.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PACKAGES = join(ROOT, "packages", "dev");
const BUILD_CONFIG = "tsconfig.bitbybit.json";
const ROOT_CONFIG = "tsconfig.build.json";
const BUILD_INFO = "./dist/tsconfig.bitbybit.tsbuildinfo";
const check = process.argv.includes("--check");

const PACKAGE_HEADER = [
    "// Generated by scripts/gen-ts-references.mjs from this package's dependencies. \"references\",",
    "// \"composite\" and \"tsBuildInfoFile\" are the generator's: change package.json and run",
    "// `npm run gen:references`. The other keys are this package's own and survive regeneration;",
    "// comments do not.",
].join("\n");
const ROOT_HEADER = "// Generated by scripts/gen-ts-references.mjs - every package that builds with tsconfig.bitbybit.json.";

function stripComments(text) {
    let out = "";
    let i = 0;
    let inString = false;
    while (i < text.length) {
        const c = text[i];
        const n = text[i + 1];
        if (inString) {
            out += c;
            if (c === "\\") { out += n ?? ""; i += 2; continue; }
            if (c === "\"") inString = false;
            i += 1;
            continue;
        }
        if (c === "\"") { inString = true; out += c; i += 1; continue; }
        if (c === "/" && n === "*") { const end = text.indexOf("*/", i + 2); i = end < 0 ? text.length : end + 2; continue; }
        if (c === "/" && n === "/") { const end = text.indexOf("\n", i); i = end < 0 ? text.length : end; continue; }
        out += c;
        i += 1;
    }
    return out;
}

function readJsonc(file) {
    try {
        return JSON.parse(stripComments(readFileSync(file, "utf8")));
    } catch (error) {
        throw new Error(`${relative(ROOT, file)}: ${error.message}`);
    }
}

const packages = readdirSync(PACKAGES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => existsSync(join(PACKAGES, entry.name, "package.json")) && existsSync(join(PACKAGES, entry.name, BUILD_CONFIG)))
    .map((entry) => ({ dir: entry.name, manifest: readJsonc(join(PACKAGES, entry.name, "package.json")) }))
    .sort((a, b) => a.dir.localeCompare(b.dir));
const dirByName = new Map(packages.map((p) => [p.manifest.name, p.dir]));

const outputs = [];
let referenceCount = 0;
for (const { dir, manifest } of packages) {
    const declared = Object.keys({ ...manifest.dependencies, ...manifest.peerDependencies });
    const siblings = declared.filter((name) => dirByName.has(name)).map((name) => dirByName.get(name)).sort();
    referenceCount += siblings.length;
    const file = join(PACKAGES, dir, BUILD_CONFIG);
    const { references: _previous, ...config } = readJsonc(file);
    const { composite: _c, tsBuildInfoFile: _b, ...own } = config.compilerOptions ?? {};
    const next = {
        ...config,
        compilerOptions: { composite: true, tsBuildInfoFile: BUILD_INFO, ...own },
        references: siblings.map((sibling) => ({ path: `../${sibling}/${BUILD_CONFIG}` })),
    };
    outputs.push({ file, text: `${PACKAGE_HEADER}\n${JSON.stringify(next, null, 4)}\n` });
}
outputs.push({
    file: join(ROOT, ROOT_CONFIG),
    text: `${ROOT_HEADER}\n${JSON.stringify({ files: [], references: packages.map((p) => ({ path: `./packages/dev/${p.dir}/${BUILD_CONFIG}` })) }, null, 4)}\n`,
});

const stale = outputs.filter((o) => !existsSync(o.file) || readFileSync(o.file, "utf8") !== o.text);
if (check) {
    if (stale.length) {
        console.error(`project references do not match the manifests in:\n  ${stale.map((o) => relative(ROOT, o.file)).join("\n  ")}\nrun \`npm run gen:references\` and commit the result`);
        process.exit(1);
    }
    console.log(`project references match the manifests (${packages.length} packages, ${referenceCount} references)`);
} else {
    for (const o of stale) writeFileSync(o.file, o.text);
    console.log(`${packages.length} packages, ${referenceCount} references, ${stale.length} file(s) written`);
}
