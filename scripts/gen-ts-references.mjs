#!/usr/bin/env node
// Generates the TypeScript project references of the workspace from the package manifests, so the
// build order has one source: packages/dev/*/package.json. Every package that builds with
// tsconfig.bitbybit.json becomes a composite project whose `references` are the @bitbybit-dev/*
// siblings it declares, and tsconfig.build.json at the root references all of them - `tsc -b`
// then orders the builds itself, and `pnpm -r run build-p` orders the staging the same way, from
// the same manifests. The build info is written INTO dist/ on purpose: tsc -b trusts it over the
// outputs when it decides a project is up to date, so it has to disappear with the dist it
// describes, or a deleted dist would "rebuild" to nothing. Each package's tsconfig.strict.json, the
// typecheck-only view (the build config with nothing emitted), is written here too, with the same
// references: references are not inherited through `extends`, and without them the view follows a
// sibling's declarations into the source of a package it never resolves through its own paths, and
// typechecks that too. The third, tsconfig.json - the view an editor and a lint run pick up, which
// unlike the build config keeps the tests and mocks in the project - is derived from the build
// config so the two cannot disagree about where a sibling resolves. `--check` writes nothing and
// exits 1 when any generated file on disk differs from what the manifests say.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PACKAGES = join(ROOT, "packages", "dev");
const BUILD_CONFIG = "tsconfig.bitbybit.json";
const ROOT_CONFIG = "tsconfig.build.json";
const BUILD_INFO = "./dist/tsconfig.bitbybit.tsbuildinfo";
const STRICT_CONFIG = "tsconfig.strict.json";
const EDITOR_CONFIG = "tsconfig.json";
const check = process.argv.includes("--check");

const PACKAGE_HEADER = [
    "// Generated by scripts/gen-ts-references.mjs from this package's dependencies. \"references\",",
    "// \"composite\" and \"tsBuildInfoFile\" are the generator's: change package.json and run",
    "// `npm run gen:references`. The other keys are this package's own and survive regeneration;",
    "// comments do not.",
].join("\n");
const ROOT_HEADER = "// Generated by scripts/gen-ts-references.mjs - every package that builds with tsconfig.bitbybit.json.";
const STRICT_HEADER = [
    "// Generated by scripts/gen-ts-references.mjs. The typecheck-only view of this package: its build config",
    "// with nothing emitted; `npm run typecheck:strict` runs it and must print nothing. The build config's",
    "// references are repeated here because references are not inherited through extends; without them the",
    "// view would follow a sibling's declarations into the source of a package this one never resolves",
    "// through its own paths.",
].join("\n");
const EDITOR_HEADER = [
    "// Generated by scripts/gen-ts-references.mjs. The view an editor and a lint run resolve for this",
    "// package: the same base and the same sibling paths as the build config, minus the emit settings and",
    "// minus its exclusions, so the tests and mocks are part of the project here. `outDir` is stated because",
    "// TypeScript excludes it by default, and a stale or misspelt one silently pulls the built dist back in",
    "// as source.",
].join("\n");

function stripComments(text) {
    let out = "";
    let i = 0;
    let inString = false;
    while (i < text.length) {
        const c = text[i];
        const n = text[i + 1];
        if (inString) {
            out += c;
            if (c === "\\") { out += n ?? ""; i += 2; continue; }
            if (c === "\"") inString = false;
            i += 1;
            continue;
        }
        if (c === "\"") { inString = true; out += c; i += 1; continue; }
        if (c === "/" && n === "*") { const end = text.indexOf("*/", i + 2); i = end < 0 ? text.length : end + 2; continue; }
        if (c === "/" && n === "/") { const end = text.indexOf("\n", i); i = end < 0 ? text.length : end; continue; }
        out += c;
        i += 1;
    }
    return out;
}

function readJsonc(file) {
    try {
        return JSON.parse(stripComments(readFileSync(file, "utf8")));
    } catch (error) {
        throw new Error(`${relative(ROOT, file)}: ${error.message}`, { cause: error });
    }
}

const packages = readdirSync(PACKAGES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .filter((entry) => existsSync(join(PACKAGES, entry.name, "package.json")) && existsSync(join(PACKAGES, entry.name, BUILD_CONFIG)))
    .map((entry) => ({ dir: entry.name, manifest: readJsonc(join(PACKAGES, entry.name, "package.json")) }))
    .sort((a, b) => a.dir.localeCompare(b.dir));
const dirByName = new Map(packages.map((p) => [p.manifest.name, p.dir]));

const outputs = [];
let referenceCount = 0;
for (const { dir, manifest } of packages) {
    const declared = Object.keys({ ...manifest.dependencies, ...manifest.peerDependencies });
    const siblings = declared.filter((name) => dirByName.has(name)).map((name) => dirByName.get(name)).sort();
    referenceCount += siblings.length;
    const file = join(PACKAGES, dir, BUILD_CONFIG);
    const { references: _previous, ...config } = readJsonc(file);
    const { composite: _c, tsBuildInfoFile: _b, ...own } = config.compilerOptions ?? {};
    const next = {
        ...config,
        compilerOptions: { composite: true, tsBuildInfoFile: BUILD_INFO, ...own },
        references: siblings.map((sibling) => ({ path: `../${sibling}/${BUILD_CONFIG}` })),
    };
    outputs.push({ file, text: `${PACKAGE_HEADER}\n${JSON.stringify(next, null, 4)}\n` });
    outputs.push({
        file: join(PACKAGES, dir, STRICT_CONFIG),
        text: `${STRICT_HEADER}\n${JSON.stringify({ extends: `./${BUILD_CONFIG}`, compilerOptions: { noEmit: true }, references: next.references }, null, 4)}\n`,
    });
    const { outDir, baseUrl, paths } = next.compilerOptions;
    outputs.push({
        file: join(PACKAGES, dir, EDITOR_CONFIG),
        text: `${EDITOR_HEADER}\n${JSON.stringify({
            extends: next.extends,
            compileOnSave: false,
            compilerOptions: { outDir, baseUrl, paths },
        }, null, 4)}\n`,
    });
}
outputs.push({
    file: join(ROOT, ROOT_CONFIG),
    text: `${ROOT_HEADER}\n${JSON.stringify({ files: [], references: packages.map((p) => ({ path: `./packages/dev/${p.dir}/${BUILD_CONFIG}` })) }, null, 4)}\n`,
});

const stale = outputs.filter((o) => !existsSync(o.file) || readFileSync(o.file, "utf8") !== o.text);
if (check) {
    if (stale.length) {
        console.error(`generated TypeScript configs are out of date in:\n  ${stale.map((o) => relative(ROOT, o.file)).join("\n  ")}\nrun \`npm run gen:references\` and commit the result`);
        process.exit(1);
    }
    console.log(`generated TypeScript configs are up to date (${packages.length} packages, ${referenceCount} references)`);
} else {
    for (const o of stale) writeFileSync(o.file, o.text);
    console.log(`${packages.length} packages, ${referenceCount} references, ${stale.length} file(s) written`);
}
